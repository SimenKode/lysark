/** The width of a letter we have no number for: that of a digit. */
const OTHER = 556;

function lookup(ranges: Ranges): Map<number, number> {
  const widths = new Map<number, number>();
  for (const [first, list] of ranges) {
    list.forEach((width, i) => {
      if (width > 0) widths.set(first + i, width);
    });
  }
  return widths;
}

const regular = lookup(REGULAR);
const bold = lookup(BOLD);

/** The width of a character in Liberation Sans, in em. */
export function charWidth(char: string, isBold: boolean): number {
  const code = char.codePointAt(0) ?? 0;
  return ((isBold ? bold : regular).get(code) ?? OTHER) / 1000;
}
